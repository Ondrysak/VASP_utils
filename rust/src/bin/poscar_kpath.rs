use std::fs;
use std::fmt::Write as FmtWrite;

use clap::Parser;
use vasp_utils::kpath::{get_bravais_kpath, KPath, KPoint};
use vasp_utils::poscar::Poscar;
use vasp_utils::symmetry::{analyze_symmetry, standardize_cell};

#[derive(Parser)]
#[command(about = "Generate VASP KPOINTS line-mode file from POSCAR using spglib")]
struct Cli {
    #[arg(short, long, default_value = "POSCAR")]
    input: String,
    #[arg(short, long, default_value = "KPOINTS")]
    output: String,
    /// Output primitive POSCAR file
    #[arg(long, default_value = "POSCAR_prim")]
    prim: String,
    /// Symmetry tolerance (Å)
    #[arg(long, default_value_t = 1e-5)]
    symprec: f64,
    /// Number of k-points per segment
    #[arg(short = 'n', long, default_value_t = 41)]
    nkpts: u32,
    /// Do not write the primitive cell POSCAR
    #[arg(long, default_value_t = false)]
    no_prim: bool,
}

fn find_point<'a>(kpath: &'a KPath, label: &str) -> Option<&'a KPoint> {
    kpath.points.iter().find(|p| p.label == label)
}

fn write_kpoints(kpath: &KPath, nkpts: u32, filename: &str) -> Result<(), String> {
    let mut buf = String::new();
    writeln!(buf, "k-path generated by poscar_kpath ({})", kpath.bravais_label).unwrap();
    writeln!(buf, "{nkpts}").unwrap();
    writeln!(buf, "Line_mode").unwrap();
    writeln!(buf, "Reciprocal").unwrap();

    for (i, seg) in kpath.segments.iter().enumerate() {
        let a = find_point(kpath, &seg.from).ok_or_else(|| {
            format!("Unknown k-point label '{}'", seg.from)
        })?;
        let b = find_point(kpath, &seg.to).ok_or_else(|| {
            format!("Unknown k-point label '{}'", seg.to)
        })?;

        writeln!(buf, "{:14.10} {:14.10} {:14.10}   ! {}", a.kx, a.ky, a.kz, a.label).unwrap();
        writeln!(buf, "{:14.10} {:14.10} {:14.10}   ! {}", b.kx, b.ky, b.kz, b.label).unwrap();

        if i + 1 < kpath.segments.len() {
            writeln!(buf).unwrap();
        }
    }

    fs::write(filename, buf).map_err(|e| format!("Error writing {filename}: {e}"))
}

fn main() {
    let cli = Cli::parse();

    if cli.nkpts == 0 {
        eprintln!("Error: --nkpts must be positive");
        std::process::exit(1);
    }

    let poscar = match Poscar::read(&cli.input) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("{e}");
            std::process::exit(1);
        }
    };

    // Standardize to conventional cell for Bravais type detection
    let conv = match standardize_cell(&poscar, cli.symprec, false, false) {
        Some(c) => c,
        None => {
            eprintln!("Error: spglib could not standardize the cell.");
            std::process::exit(1);
        }
    };

    // Primitive cell — needed for aP orientation reference
    let prim_early = match standardize_cell(&poscar, cli.symprec, true, false) {
        Some(p) => p,
        None => {
            eprintln!("Error: spglib could not generate primitive cell.");
            std::process::exit(1);
        }
    };

    let dataset = match analyze_symmetry(&conv, cli.symprec) {
        Some(d) => d,
        None => {
            eprintln!("Error: spglib symmetry analysis failed.");
            std::process::exit(1);
        }
    };
    let intl = &dataset.international_symbol;
    println!("Space group: {intl} (#{})", dataset.spacegroup_number);

    // Pass the as-read POSCAR as orientation reference for aP subcase detection.
    let kpath = match get_bravais_kpath(&conv, &poscar, &dataset) {
        Some(k) => k,
        None => {
            eprintln!(
                "Error: Bravais lattice type not supported.\n  (international symbol: {intl})\n  \
                 Supported: cP cF cI  tP tI  oP oF oI oC  hP hR  mP mC  aP"
            );
            std::process::exit(1);
        }
    };

    println!("Bravais type: {}", kpath.bravais_label);
    println!(
        "Segments: {}  Special points: {}",
        kpath.segments.len(),
        kpath.points.len()
    );

    if let Err(e) = write_kpoints(&kpath, cli.nkpts, &cli.output) {
        eprintln!("{e}");
        std::process::exit(1);
    }
    println!("Written: {}", cli.output);

    if !cli.no_prim {
        if let Err(e) = prim_early.write(&cli.prim) {
            eprintln!("Warning: failed to write {}: {e}", cli.prim);
        } else {
            println!(
                "Written: {} (use this POSCAR for the band structure run)",
                cli.prim
            );
        }
    }
}
